export const DESTINATIONS: Destination[] = [
  ...DOMESTIC_DESTINATIONS,
  ...OVERSEAS_DESTINATIONS,
];

export function getDestinationById(id: string): Destination | undefined {
  return DESTINATIONS.find((destination) => destination.id === id);
}

export function getDestinationsByRegion(
  region: DestinationRegion,
): Destination[] {
  return DESTINATIONS.filter((destination) => destination.region === region);
}

/** 같은 국가(해외) 또는 동일 지역 구분(국내) 기준 관련 여행지를 최대 6개 반환한다(REQ-FUNC-009). */
export function getRelatedDestinations(id: string, limit = 6): Destination[] {
  const current = getDestinationById(id);
  if (!current) {
    return [];
  }
  return DESTINATIONS.filter(
    (destination) =>
      destination.id !== current.id &&
      destination.region === current.region &&
      destination.country === current.country,
  ).slice(0, limit);
}
